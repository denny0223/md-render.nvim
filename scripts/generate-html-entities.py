"""Generate the offline Lua table from a verified WHATWG entities.json download.

curl -fsSL https://html.spec.whatwg.org/entities.json -o /tmp/entities.json
python scripts/generate-html-entities.py /tmp/entities.json > lua/md-render/html_entities.lua
"""

