if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: generate-html-entities.py /path/to/entities.json")
    source = Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        sys.exit("entities.json does not match the verified source SHA-256")
    entries = json.loads(source)
    lines = [HEADER]
    for name, entry in sorted(entries.items()):
        if not name.endswith(";"):
            continue
        assert re.fullmatch(r"&[A-Za-z][A-Za-z0-9]*;", name), name
        assert entry["characters"] == "".join(map(chr, entry["codepoints"])), name
        value = "".join(f"\\u{{{ord(char):X}}}" for char in entry["characters"])
        lines.append(f'  ["{name[1:-1]}"] = "{value}",\n')
    lines.append("}\n")
    sys.stdout.write("".join(lines))
